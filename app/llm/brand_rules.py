# pattern -> この文字列を含む場合はマッチを無効化する（前方一致の偶然衝突対策）。
# 例: "ブリリア"は"ブリリアント"（装飾的な一般語）に前方一致してしまうため除外する。
NEGATIVE_PATTERNS: dict[str, list[str]] = {
    "ブリリア": ["ブリリアント"],
}


def _normalize(text: str) -> str:
    """
    比較用正規化: NFKC + 空白/括弧記号の除去。
    中黒(・)は除去しない: 除去すると「〇〇パーク・マンション」のような、
    中黒で意味的に区切られた一般名（パーク+マンション）が「パークマンション」
    ブランドと偶然一致してしまう事例が見つかったため（2026-08）。
    "ザ・パークハウス"のような中黒を含む正式表記は、"ザパークハウス"
    （中黒なし）とセットで別パターンとして個別登録することで対応する。
    """
    text = unicodedata.normalize("NFKC", text)
    return re.sub(r"[\s\-\(\)（）.,]", "", text)


# 全パターンを文字列長の降順でソートしておく。マッチングはこの順で行うことで、
# 「プラウドフラット」のような具体的な下位ブランド名が、「プラウド」のような
# 短い上位ブランド名より優先してマッチするようにする（tierグループ単位で
# 上から順にチェックする方式だと、短い汎用パターンが先に確定してしまい、
# より具体的なパターンが永遠に評価されないバグがあったため）。
_ALL_PATTERNS_SORTED: list[tuple[int, str]] = sorted(
    ((tier, pattern) for tier, patterns in BRAND_TIERS.items() for pattern in patterns),
    key=lambda tp: len(_normalize(tp[1])),
    reverse=True,
)


def classify_brand_tier(title: str | None) -> tuple[int, str | None]:
    """
    建物名からブランドティア(1-5)を判定する。

    Returns:
        (tier, matched_pattern) — matched_patternはマッチしたブランド名
        （監査用）。どのブランドにも該当しない場合は (1, None)。
    """
    if not title:
        return 1, None

    normalized = _normalize(title)
    for tier, pattern in _ALL_PATTERNS_SORTED:
        if _normalize(pattern) not in normalized:
            continue
        negatives = NEGATIVE_PATTERNS.get(pattern, [])
        if any(_normalize(neg) in normalized for neg in negatives):
            continue  # 偶然の前方一致衝突として除外し、次のパターンを試す
        return tier, pattern
    return 1, None
